import { mkdir, copyFile, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../public/downloads/', import.meta.url);
await mkdir(target, { recursive: true });
const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error('Run through npm run pack:cli');
const { version } = JSON.parse(await readFile(new URL('../cli/package.json', import.meta.url), 'utf8'));
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+(?:-[\w.-]+)?(?:\+[\w.-]+)?$/.test(version)) throw new Error('CLI package has an invalid version.');
const output = execFileSync(process.execPath, [npmCli, 'pack', '--json'], { cwd: root + 'cli', encoding: 'utf8' });
const filename = JSON.parse(output)[0].filename;
const archive = new URL('../cli/' + filename, import.meta.url);
const versioned = `traqiva-cli-${version}.tgz`;
await copyFile(archive, new URL(versioned, target));
await copyFile(archive, new URL('../public/cli.tgz', import.meta.url));
console.log(`Prepared public/downloads/${versioned} and public/cli.tgz`);
